    p("## 3. 潜在风险与优化")
    p("")
    p("### 3.1 Jest API 覆盖缺口")
    p("")
    p("虽然 Bun 自称是 Jest 的即插即用替代品，但在实际迁移中，有几个关键的 API 缺口需要特别注意。了解这些缺口可以帮助团队做出更明智的迁移决策，并制定有效的替代方案。")
    p("")
    p("**高危缺口（可能导致测试完全无法运行）：**")
    p("")
    p("| 缺失 API | 影响范围 | 替代方案 | 迁移难度 |")
    p("|----------|---------|----------|----------|")
    p("| `jest.mock('module')` | 模块级 Mock | 使用依赖注入或 Proxy | 高 |")
    p("| `jest.requireActual()` | 获取原始模块 | 直接 import | 低 |")
    p("| `jest.isolateModules()` | 隔离模块状态 | 自行管理模块缓存 | 中 |")
    p("| `jest.useFakeTimers('modern')` | 假定时器 | 使用 fakeTimers（有限支持） | 中 |")
    p("")
    p("**中低危缺口（可能导致特定测试失败）：**")
    p("")
    p("| 缺失 API | 影响范围 | 替代方案 | 迁移难度 |")
    p("|----------|---------|----------|----------|")
    p("| `jest.spyOn(obj, 'method', 'get')` | Getter Mock | 使用 Object.defineProperty | 低 |")
    p("| `expect.extend()` | 自定义断言 | 自行封装辅助函数 | 低 |")
    p("| `expect.addSnapshotSerializer()` | 自定义序列化器 | 暂不支持 | 高 |")
    p("| `jest.setSystemTime()` | 系统时间控制 | 手动模拟 Date | 低 |")
    p("| `jest.retryTimes()` | 重试失败用例 | 暂不支持 | 中 |")
    p("| `jest.replaceProperty()` | 属性替换 | 使用 Object.defineProperty | 低 |")
    p("")
    p("**迁移前的兼容性检查清单：**")
    p("1. 运行 grep 检查高危 API 使用情况")
    p("2. 运行 grep 检查自定义断言和序列化器")
    p("3. 运行 grep 检查其他不兼容 API")
    p("4. 检查 CI/CD 配置中是否有 Jest 特定的参数")
    p("5. 检查 jest.config.js 中是否有自定义 transformer 或 resolver")
    p("")
    p("### 3.2 快照格式差异")
    p("")
    p("Bun 和 Jest 的快照格式虽然大体相同，但在细节上存在差异。当团队在 Bun 和 Jest 之间切换时，这些差异可能导致快照测试的不稳定。")
    p("")
    p("**已知的格式差异：**")
    p("")
    p("1. **数值精度** — Bun 对浮点数的序列化与 Jest 不同。")
    p("2. **属性排序** — Bun 使用 JavaScriptCore 引擎，而 Jest 运行在 V8 引擎上，两者对属性的排序规则在边界情况下有所不同。")
    p("3. **Symbol 键** — Bun 的快照序列化器默认跳过 Symbol 类型的属性键，Jest 也是如此，但如果使用了 `Object.getOwnPropertySymbols()`，两者的行为可能不一致。")
    p("4. **Error 对象** — Bun 和 Jest 对 Error 对象的序列化方式不同，特别是在 stack trace 的格式上。")
    p("")
    p("**最佳实践：**")
    p("- 在同一个项目中不要混用 Bun 和 Jest 的快照，保持一致性")
    p("- 迁移时使用 `bun test -u` 重新生成所有快照，确保基线一致")
    p("- 在 CI 中确保所有开发者和 CI 环境使用相同的 Bun 版本")
    p("- 定期审查快照文件，删除不再使用的快照，避免快照文件膨胀")
    p("- 将快照文件的变更纳入代码审查流程，确保每次快照更新都是有意为之")
    p("")
    p("### 3.3 happy-dom 替代 jsdom 的影响")
    p("")
    p("Bun 选择 happy-dom 作为其 DOM 实现，这是一个有争议的决定。happy-dom 虽然在性能上优于 jsdom，但在 API 完备度上存在差距。")
    p("")
    p("**happy-dom 已知缺失的 API：**")
    p("")
    p("1. **Canvas API** — `HTMLCanvasElement.getContext('2d')` 在 happy-dom 中返回 `null`。这意味着依赖于 Canvas 的图表库、图像处理库和游戏引擎的测试将无法运行。")
    p("2. **SVG 相关 API** — 虽然 happy-dom 支持基本的 SVG 元素创建和操作，但复杂的 SVG 操作可能不可用。")
    p("3. **部分 Form 相关 API** — 如 `HTMLFormElement.requestSubmit()` 和 `HTMLFormElement.reportValidity()` 在 happy-dom 中未实现。")
    p("4. **Drag and Drop API** — `DataTransfer` 和拖放事件的支持有限。")
    p("5. **Range API** — `document.createRange()` 在 happy-dom 中的实现不完全。")
    p("")
    p("**影响评估：**")
    p("- 对于使用 React、Vue、Svelte 等主流框架的组件测试，happy-dom 的覆盖范围通常足够")
    p("- 对于使用可视化库（D3.js、Three.js、ECharts、Chart.js）的项目，需要额外的测试策略")
    p("- 对于涉及 Canvas 或复杂 SVG 的操作，建议使用浏览器的真实环境进行测试")
    p("- 对于大多数业务组件和页面级别的测试，happy-dom 提供的功能已经足够")
    p("")
    p("**迁移策略：**")
    p("```typescript")
    p("// 检测 DOM 实现")
    p('if (typeof window !== "undefined" && !window.CanvasRenderingContext2D) {')
    p('  console.warn("当前环境不支持 Canvas API，请使用真实浏览器运行这些测试");')
    p("}")
    p("")
    p("// 条件跳过不兼容的测试")
    p('const itIfCanvas = typeof CanvasRenderingContext2D !== "undefined" ? it : it.skip;')
    p('itIfCanvas("Canvas 渲染测试", () => {')
    p("  // Canvas 相关测试")
    p("});")
    p("```")
    p("")
    p("### 3.4 大型测试套件的性能优化")
    p("")
    p("虽然 Bun 在小型和中型项目中表现出色，但在大型测试套件（1000+ 测试文件）中，仍然需要一些优化策略来保持性能。")
    p("")
    p("**瓶颈分析：**")
    p("")
    p("大型测试套件的性能瓶颈通常出现在以下几个环节：")
    p("")
    p("1. **文件 I/O** — 虽然 Bun 的文件扫描速度很快，但当测试文件数量超过 5000 时，文件扫描时间仍然可能成为瓶颈。")
