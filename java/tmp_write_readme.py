    p("## 4. 典型问题处理")
    p("")
    p("### 4.1 expect API 无法工作")
    p("")
    p("**症状：** 从 `@jest/globals` 或 `expect` 包导入的 `expect` 函数在 `bun test` 中报错，错误信息通常是 expect is not defined 或类似的内容。")
    p("")
    p("**原因：** `bun test` 的断言 API 必须从 `bun:test` 模块导入。如果使用了第三方 `expect` 包（如 `@jest/globals`、`chai`、`expect` 等），Bun 不会自动提供兼容性包装。")
    p("")
    p("**解决方案：**")
    p("")
    p("```typescript")
    p('// 错误：从 Jest 导入')
    p('import { expect } from "@jest/globals";')
    p("")
    p('// 正确：从 bun:test 导入')
    p('import { expect, describe, it } from "bun:test";')
    p("")
    p("// 也可以全局使用（Bun 会自动注入 describe/it/expect）")
    p('describe("测试", () => {')
    p('  it("工作正常", () => {')
    p("    expect(1 + 1).toBe(2);")
    p("  });")
    p("});")
    p("```")
    p("")
    p("### 4.2 Mock 机制不生效")
    p("")
    p("**症状：** 使用 `jest.mock()` 或 `mock()` 时，模块的原始实现被调用，而不是 mock 版本。")
    p("")
    p("**原因分析：**")
    p("")
    p("原因一：**导入顺序问题** — `jest.mock()` 在 Jest 中会被提升到文件顶部执行，但 `bun test` 中的 `mock()` 不会被提升。")
    p("")
    p("```typescript")
    p('// 在 Bun 中不生效')
    p('import { db } from "./database";')
    p('import { mock } from "bun:test";')
    p('mock(db, "query", () => "mocked");')
    p("")
    p('// 正确的做法：使用 spyOn 替代')
    p("const db = { query: () => \"original\" };")
    p('const spy = spyOn(db, "query");')
    p('spy.mockImplementation(() => "mocked");')
    p("```")
    p("")
    p("原因二：**模块缓存** — Bun 的模块加载器会缓存已加载的模块。如果在模块加载后尝试 mock，mock 不会生效。")
    p("")
    p("```typescript")
    p('import * as math from "./math";')
    p('const spy = spyOn(math, "add");')
    p("spy.mockImplementation(() => 999);")
    p("```")
    p("")
    p("原因三：**const 声明** — 如果模块导出的函数是用 `const` 声明的，则无法被 `spyOn` 替换。")
    p("")
    p("```typescript")
    p("// math.ts")
    p("export const add = (a, b) => a + b; // const 导出，无法被 spyOn")
    p("")
    p("// 推荐的导出方式")
    p("export function add(a, b) { return a + b; }")
    p("")
    p("// 或者使用对象包裹")
    p("export const math = { add: (a, b) => a + b };")
    p("```")
    p("")
    p("### 4.3 快照更新失败")
    p("")
    p("**症状：** 修改了组件输出后，快照测试失败，但使用 `--update-snapshots` 标志更新快照时出现问题。")
    p("")
    p("**常见问题：**")
    p("")
    p("**问题 1：快照文件被忽略**")
    p("```bash")
    p("git add __snapshots__/")
    p("```")
    p("")
    p("**问题 2：部分更新**")
    p("```bash")
    p("bun test --update-snapshots")
    p("```")
    p("")
    p("**问题 3：快照匹配模式不生效**")
    p("```typescript")
    p("// Bun 目前不支持内联快照")
    p("expect(value).toMatchSnapshot();")
    p("```")
    p("")
    p("### 4.4 测试超时")
    p("")
    p("**症状：** 异步测试因超时而失败，错误信息为 Test timed out after X ms。")
    p("")
    p("**原因分析：**")
    p("")
    p("1. **默认超时时间不足** — Bun 的默认测试超时时间是 5000 毫秒（5 秒），对于涉及网络请求、数据库操作或文件 I/O 的测试可能不够。")
    p("2. **死锁** — Promise 没有 resolve 或 reject，导致测试永远挂起。")
    p("3. **资源泄露** — 数据库连接、HTTP 服务器等资源没有正确释放。")
    p("")
    p("**解决方案：**")
    p("")
    p("```typescript")
    p('it("数据库查询", async () => {')
    p("  // 测试逻辑")
    p("}, 30000);")
    p("```")
    p("")
    p("**常见的超时陷阱：**")
    p("1. **忘记 await** — 异步测试中忘记使用 `await` 关键字")
    p("2. **beforeAll 中的异步操作** — `beforeAll` 钩子中的异步操作如果没有正确 await")
    p("3. **afterAll 清理失败** — 资源清理操作挂起")
    p("4. **无限循环** — 测试代码中存在未终止的循环或递归")
    p("")
    p("---")
    p("")
    p("## 5. 必备知识与技能")
    p("")
    p("### 5.1 测试金字塔理论")
    p("")
    p("测试金字塔是软件测试领域最经典的策略模型之一，由 Mike Cohn 在其著作《Succeeding with Agile》中提出。该模型将测试分为三个层次，从底向上呈金字塔形状。")
    p("")
    p("```")
    p("        /\\")
    p("       /  \\          E2E 测试（少量）")
    p("      /    \\")
    p("     /------\\")
    p("    /        \\       集成测试（适量）")
    p("   /          \\")
    p("  /------------\\")
    p(" /              \\    单元测试（大量）")
    p("/----------------\\")
    p("```")
    p("")
    p("**三层架构详解：**")
    p("")
    p("**第一层：单元测试（底层，大量）**")
    p("- 测试范围：单个函数、方法或类")
    p("- 执行速度：极快（毫秒级），可以频繁运行")
    p("- 依赖：无外部依赖（数据库、网络、文件系统），完全隔离")
    p("- 目标：验证业务逻辑的正确性")
    p("- 比例：占总测试的 70-80%")
    p("- 工具：bun test + mock")
    p("")
    p("**第二层：集成测试（中层，适量）**")
    p("- 测试范围：多个模块的交互")
    p("- 执行速度：中等（秒级），适合在 CI 中运行")
    p("- 依赖：可能需要轻量级的测试基础设施")
    p("- 目标：验证模块间的协作是否正确")
    p("- 比例：占总测试的 15-20%")
    p("- 工具：bun test + Bun.serve + happy-dom")
    p("")
    p("**第三层：E2E 测试（顶层，少量）**")
    p("- 测试范围：完整的用户场景")
    p("- 执行速度：慢（分钟级），只在关键路径上运行")
    p("- 依赖：完整的测试环境（数据库、服务、浏览器）")
    p("- 目标：验证系统是否满足业务需求")
    p("- 比例：占总测试的 5-10%")
    p("- 工具：Playwright、Cypress、Selenium")
    p("")
    p("**反模式警示：**")
    p("")
    p("**冰淇淋甜筒** — 测试金字塔的倒置版本，E2E 测试多于单元测试。这种模式导致测试运行时间过长，定位问题困难，维护成本高昂。")
    p("")
    p("**冰激凌圣代** — 单元测试和集成测试太少，主要依赖 E2E 测试。这种模式同样会导致测试效率低下。")
    p("")
    p("**纸杯蛋糕** — 所有测试都集中在中间层（集成测试），底层和顶层测试不足。")
    p("")
    p("### 5.2 Mock / Stub / Spy 的区别")
    p("")
    p("在测试中，模拟是一个总称，下面细分为 Mock、Stub 和 Spy 三种不同的技术。理解它们的区别对于编写高质量的测试至关重要。")
    p("")
    p("**概念对比表：**")
    p("")
    p("| 维度 | Mock | Stub | Spy |")
    p("|------|------|------|-----|")
    p("| 核心目的 | 验证交互行为 | 提供预设返回值 | 观察实际调用 |")
    p("| 是否保留原始行为 | 否 | 否 | 是 |")
    p("| 是否验证调用次数 | 是 | 通常不验证 | 是 |")
    p("| 是否验证调用参数 | 是 | 通常不验证 | 是 |")
    p("| 是否提供返回值 | 是 | 是 | 可以（通过配置） |")
    p("| 典型用途 | 验证外部服务调用 | 替换依赖 | 观察方法调用 |")
    p("")
    p("**Mock 详解：**")
    p("")
    p("Mock 是最彻底的模拟方式。它不仅替换了被模拟对象的行为，还允许测试代码验证该对象是否被正确调用。Mock 的核心关注点是交互验证，即验证被测试代码是否正确地与它的协作者进行了交互。")
    p("")
    p("```typescript")
    p('it("注册成功后发送欢迎邮件", () => {')
    p("  const sendEmail = mock(() => true);")
    p("  const userService = new UserService({ emailService: { send: sendEmail } });")
    p('  userService.register({ email: "test@example.com" });')
    p("  expect(sendEmail).toHaveBeenCalledTimes(1);")
    p('  expect(sendEmail).toHaveBeenCalledWith("test@example.com", expect.stringContaining("欢迎"));')
    p("});")
    p("```")
    p("")
    p("**Stub 详解：**")
    p("")
    p("Stub 关注的是提供什么，而不是是否被调用。Stub 用来替换那些难以在测试环境中运行的依赖（如数据库、网络服务等），为被测代码提供确定性的输入。")
    p("")
    p("```typescript")
    p('it("根据 ID 获取用户信息", () => {')
    p("  const dbStub = {")
    p("    query: (sql) => [{ id: 1, name: \"张三\" }],")
    p("  };")
    p("  const userService = new UserService(dbStub);")
    p("  const user = userService.findById(1);")
    p('  expect(user.name).toBe("张三");')
    p("});")
    p("```")
    p("")
    p("**Spy 详解：**")
    p("")
    p("Spy 是 Mock 和 Stub 的折中方案。它包装了真实对象的方法，允许在保留原始行为的同时追踪调用信息。")
    p("")
    p("```typescript")
    p('it("处理请求时记录日志", () => {')
    p("  const logger = { info: (msg) => console.log(msg) };")
    p('  const spy = spyOn(logger, "info");')
    p("  const handler = new RequestHandler(logger);")
    p("  handler.process({ id: 1 });")
    p("  expect(spy).toHaveBeenCalled();")
    p("  spy.mockRestore();")
    p("});")
    p("```")
