    p("### 5.3 TDD 方法论")
    p("")
    p("测试驱动开发（Test-Driven Development, TDD）是 Kent Beck 在 Extreme Programming 中提出的开发方法论，其核心是测试先于代码。")
    p("")
    p("**TDD 的三大法则（Robert C. Martin）：**")
    p("")
    p("1. 在编写生产代码之前，先编写失败的测试")
    p("2. 不要编写超过使测试通过所需的生产代码")
    p("3. 不要编写超过使当前失败测试通过所需的测试")
    p("")
    p("**TDD 的循环周期（红-绿-重构）：**")
    p("")
    p("```")
    p("+-------------------------------------------------+")
    p("|  红（Red）: 编写失败的测试                         |")
    p("|  - 编写一个测试，描述一个期望的行为                  |")
    p("|  - 运行测试，确认它失败（红色）                     |")
    p("+------------------------+------------------------+")
    p("                         |")
    p("                         v")
    p("+-------------------------------------------------+")
    p("|  绿（Green）: 让测试通过                          |")
    p("|  - 编写最少的生产代码使测试通过                    |")
    p("|  - 不追求优雅，只追求通过                          |")
    p("+------------------------+------------------------+")
    p("                         |")
    p("                         v")
    p("+-------------------------------------------------+")
    p("|  重构（Refactor）: 优化代码                        |")
    p("|  - 在测试的保护下重构生产代码                      |")
    p("|  - 消除重复代码，改善设计                          |")
    p("|  - 确保测试仍然通过                               |")
    p("+------------------------+------------------------+")
    p("                         |")
    p("                         +---------> 回到红阶段")
    p("```")
    p("")
    p("**TDD 的优势：**")
    p("1. 更高的代码覆盖率 — 每个功能都有对应的测试")
    p("2. 更好的设计 — 测试先行的方式迫使代码更模块化、更可测试")
    p("3. 更少的调试时间 — 问题在开发阶段就被发现")
    p("4. 更安全的重构 — 测试提供了安全网")
    p("5. 活的文档 — 测试代码描述了系统的行为")
    p("")
    p("**Bun 对 TDD 的支持：**")
    p("- 极快的反馈循环 — `bun test` 的毫秒级启动速度让 TDD 的红-绿循环更加流畅")
    p("- `--watch` 模式 — 自动重新运行测试，实现持续反馈")
    p("- TypeScript 原生支持 — 无需额外配置即可在测试中使用 TypeScript")
    p("")
    p("### 5.4 代码覆盖率指标")
    p("")
    p("代码覆盖率是衡量测试质量的重要指标，但它也经常被误解和误用。Bun 内置了代码覆盖率收集功能，通过 `--coverage` 标志启用。")
    p("")
    p("**覆盖率指标详解：**")
    p("")
    p("| 指标 | 定义 | 重要性 |")
    p("|------|------|--------|")
    p("| 行覆盖率 | 被执行的代码行数 / 总行数 | 基础指标，容易达成但可能误导 |")
    p("| 分支覆盖率 | 被执行的分支数 / 总分指数 | 重要指标，反映逻辑路径的覆盖 |")
    p("| 函数覆盖率 | 被调用的函数数 / 总函数数 | 中等重要性 |")
    p("| 语句覆盖率 | 被执行的语句数 / 总语句数 | 与行覆盖率类似 |")
    p("")
    p("```bash")
    p("bun test --coverage")
    p("bun test --coverage --coverage-reporter=html")
    p("```")
    p("")
    p("**覆盖率陷阱与正确理解：**")
    p("")
    p("**陷阱 1：100% 覆盖率不等于无 Bug**")
    p("```typescript")
    p("function divide(a, b) { return a / b; }")
    p("// 测试没有覆盖到 b=0 的情况")
    p("```")
    p("")
    p("**陷阱 2：盲目追求覆盖率数字**")
    p("- 编写大量无意义的测试（测试 getter/setter）")
    p("- 忽视重要的边界条件")
    p("- 测试代码比生产代码还多")
    p("")
    p("**陷阱 3：忽略分支覆盖率**")
    p("```typescript")
    p("function classifyAge(age) {")
    p('  if (age < 18) return "未成年";')
    p('  if (age >= 60) return "老年";')
    p('  return "成年";')
    p("}")
    p("// 如果只测试 age=25，行覆盖率 100%，但分支覆盖率只有 33%")
    p("```")
