    p("4. **mock 函数配合重导出** — 在测试文件中重新导出被 mock 的函数，通过重导出层实现拦截。")
    p("")
    p("### 2.4 快照比较算法")
    p("")
    p("Bun 的快照机制与 Jest 类似，但在底层实现上有所不同。理解这些差异对于避免快照测试的意外失败非常重要。")
    p("")
    p("**快照生成流程：**")
    p("")
    p("```")
    p("第一次运行测试")
    p("    |")
    p("    遇到 toMatchSnapshot() 断言")
    p("    |")
    p("    将实际值序列化为字符串")
    p("    |")
    p("    写入 .snap 文件（在 __snapshots__ 目录下）")
    p("    |")
    p("    测试通过")
    p("")
    p("后续运行")
    p("    |")
    p("    遇到 toMatchSnapshot() 断言")
    p("    |")
    p("    将实际值序列化为字符串")
    p("    |")
    p("    读取对应的 .snap 文件")
    p("    |")
    p("    逐字符比较 --> 匹配 --> 测试通过")
    p("              --> 不匹配 --> 测试失败")
    p("```")
    p("")
    p("**序列化算法的差异：**")
    p("")
    p("Bun 在序列化值时使用的算法与 Jest 的 `pretty-format` 库不同。Bun 使用自己的序列化器，它在处理以下场景时有细微差异：")
    p("")
    p("1. **Date 对象** — Bun 使用 `Date.prototype.toISOString()` 进行序列化，而 Jest 可能使用不同的格式。")
    p("2. **Set 和 Map** — Bun 保持插入顺序，Jest 也保持插入顺序，但格式化方式不同。")
    p("3. **类实例** — Bun 序列化类实例时只序列化可枚举属性，而 Jest 可能包括原型链上的属性。")
    p("4. **循环引用** — Bun 使用 `[Circular]` 标记，Jest 也使用 `[Circular]` 但位置略有不同。")
    p("")
    p("**快照更新策略：**")
    p("")
    p("Bun 通过 `--update-snapshots`（或缩写 `-u`）标志来更新快照：")
    p("")
    p("```bash")
    p("bun test --update-snapshots")
    p("bun test -u")
    p("```")
    p("")
    p("当指定此标志时，Bun 会：")
    p("1. 重新运行所有测试，确保每个断言都有最新的输出")
    p("2. 对于每个 `toMatchSnapshot()` 断言，用新的值覆盖旧的快照")
    p("3. 删除不再被任何测试引用的旧快照，避免快照文件膨胀")
    p("4. 将更新后的快照写入磁盘，确保文件系统同步")
    p("")
